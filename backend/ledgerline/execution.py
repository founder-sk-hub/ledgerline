"""Human approval gate and execution. No model is involved after approval: execution is deterministic.

Execution writes a SEPA credit-transfer file (pain.001.001.09) for the bank and puts approved
emails in an outbox folder. Nothing is transmitted - uploading the file to the bank stays a
human step by design.
"""

from __future__ import annotations

import time
from datetime import datetime, timezone
from email.message import EmailMessage
from pathlib import Path
from xml.sax.saxutils import escape

from .config import RUNTIME
from .tools import r2

APPROVABLE_PREFIXES = ("pay:", "email:", "doc:")


def approval_items(st: dict) -> list[dict]:
    """Everything a human must decide on, with the current decision."""
    items = []
    for it in (st["payment_batch"] or {}).get("items", []):
        items.append({"item": f"pay:{it['vendor_id']}", "kind": "payment", "payload": it})
    for e in st["emails"]:
        items.append({"item": f"email:{e['email_id']}", "kind": "email", "payload": e})
    for d in st["docs"]:
        if d["final_status"] == "escalate":
            items.append({"item": f"doc:{d['doc_id']}", "kind": "escalation", "payload": {
                "doc_id": d["doc_id"], "filename": d["filename"], "decision": d["decision"],
                "verification": d["verification"], "extraction": d["extraction"]}})
    for i in items:
        i["decision"] = st["approvals"].get(i["item"], {}).get("decision", "pending")
    return items


def build_execution(st: dict, run_id: str) -> dict:
    items = {i["item"]: i for i in approval_items(st)}
    payments = []
    for key, i in items.items():
        if i["kind"] == "payment" and i["decision"] == "approved":
            payments.append({**i["payload"], "approved_by": st["approvals"][key].get("actor", "human")})
        # Reviewing an exception cannot create a payment from untrusted extracted
        # bank details. Correct its records and produce a new reviewed batch first.
    out_dir = RUNTIME / "exports" / run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    batch = st["payment_batch"] or {}
    sepa_path = None
    if payments:
        sepa_path = out_dir / "pain001.xml"
        sepa_path.write_text(sepa_xml(run_id, batch.get("debtor", {}), batch.get("execution_date", ""), payments))
    outbox = out_dir / "outbox"
    outbox.mkdir(exist_ok=True)
    queued = []
    for key, i in items.items():
        if i["kind"] == "email" and i["decision"] == "approved":
            e = i["payload"]
            msg = EmailMessage()
            msg["To"] = f"{e['to_name']} <{e['to']}>"
            msg["Subject"] = e["subject"]
            msg.set_content(e["body"])
            (outbox / f"{e['email_id']}.eml").write_bytes(bytes(msg))
            queued.append({"email_id": e["email_id"], "to": e["to"], "subject": e["subject"]})
    return {"payments": payments, "total": r2(sum(p["amount"] for p in payments)),
            "sepa_file": sepa_path.name if sepa_path else None, "emails_queued": queued,
            "note": "Nothing was transmitted: upload the SEPA file to your bank and send the outbox emails yourself."}


def sepa_xml(run_id: str, debtor: dict, execution_date: str, payments: list[dict]) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")
    msg_id = f"LL-{run_id[:12]}-{int(time.time())}"
    total = r2(sum(p["amount"] for p in payments))
    tx = []
    for i, p in enumerate(payments, 1):
        bic = f"<CdtrAgt><FinInstnId><BICFI>{escape(p['bic'])}</BICFI></FinInstnId></CdtrAgt>" if p.get("bic") else ""
        tx.append(f"""      <CdtTrfTxInf>
        <PmtId><EndToEndId>{escape(msg_id)}-{i:03d}</EndToEndId></PmtId>
        <Amt><InstdAmt Ccy="EUR">{p['amount']:.2f}</InstdAmt></Amt>
        {bic}
        <Cdtr><Nm>{escape(str(p['vendor_name'])[:70])}</Nm></Cdtr>
        <CdtrAcct><Id><IBAN>{escape(p['iban'])}</IBAN></Id></CdtrAcct>
        <RmtInf><Ustrd>{escape(p['reference'][:140])}</Ustrd></RmtInf>
      </CdtTrfTxInf>""")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Ledgerline from a human-approved batch. SYNTHETIC demo data - do not upload to a bank. -->
<Document xmlns="urn:iso:std:iso:20022:tech:xsd:pain.001.001.09">
  <CstmrCdtTrfInitn>
    <GrpHdr>
      <MsgId>{escape(msg_id)}</MsgId><CreDtTm>{now}</CreDtTm>
      <NbOfTxs>{len(payments)}</NbOfTxs><CtrlSum>{total:.2f}</CtrlSum>
      <InitgPty><Nm>{escape(debtor.get('name', ''))}</Nm></InitgPty>
    </GrpHdr>
    <PmtInf>
      <PmtInfId>{escape(msg_id)}-1</PmtInfId><PmtMtd>TRF</PmtMtd>
      <NbOfTxs>{len(payments)}</NbOfTxs><CtrlSum>{total:.2f}</CtrlSum>
      <PmtTpInf><SvcLvl><Cd>SEPA</Cd></SvcLvl></PmtTpInf>
      <ReqdExctnDt><Dt>{escape(execution_date)}</Dt></ReqdExctnDt>
      <Dbtr><Nm>{escape(debtor.get('name', ''))}</Nm></Dbtr>
      <DbtrAcct><Id><IBAN>{escape(debtor.get('iban', ''))}</IBAN></Id></DbtrAcct>
      <DbtrAgt><FinInstnId><Othr><Id>NOTPROVIDED</Id></Othr></FinInstnId></DbtrAgt>
      <ChrgBr>SLEV</ChrgBr>
{chr(10).join(tx)}
    </PmtInf>
  </CstmrCdtTrfInitn>
</Document>
"""


def export_dir(run_id: str) -> Path:
    return RUNTIME / "exports" / run_id
